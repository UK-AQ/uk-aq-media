import { readFileSync, writeFileSync } from 'node:fs';
import { SourceSchema, z } from '@uk-aq-media/core';

const sources = z.array(SourceSchema).length(10).parse(
  JSON.parse(readFileSync('config/sources.seed.json', 'utf8')),
);
if (new Set(sources.map(s => s.source_key)).size !== sources.length) throw new Error('duplicate_source');
const quote = (value: string | number): string => typeof value === 'number' ? String(value) :
  `'${value.replaceAll("'", "''")}'`;
const columns = ['source_key', 'name', 'canonical_domain', 'source_type', 'enabled',
  'publication_policy', 'review_level', 'priority', 'discovery_method', 'discovery_config_json',
  'content_fetch_policy', 'ai_content_policy', 'image_policy'];
// 0002 is an applied immutable baseline. Later migrations advance AQN and Guardian;
// regenerating the historical seed must therefore preserve both original states.
const initialSources = sources.map(source => {
  if (source.source_key === 'air-quality-news') {
    return { ...source, content_fetch_policy: 'discovery_metadata_only' as const };
  }
  if (source.source_key === 'the-guardian') {
    return { ...source, enabled: false, discovery_method: 'deferred' as const,
      discovery_config: { retain_excerpt: false as const }, image_policy: 'blocked' as const };
  }
  return source;
});
const sql = '-- Generated by npm run seed:generate from config/sources.seed.json.\n' +
  '-- Initial inserts only; never overwrite operational source policies on replay.\n' +
  initialSources.map(({ discovery_config, enabled, ...source }) => {
    const row: Record<string, string | number> = { ...source, enabled: Number(enabled),
      discovery_config_json: JSON.stringify(discovery_config) };
    return `INSERT INTO media_sources (${columns.join(', ')})\nVALUES (${columns.map(c => quote(row[c]!)).join(', ')})\nON CONFLICT(source_key) DO NOTHING;\n`;
  }).join('\n');
const destination = 'migrations/0002_launch_sources.sql';
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== sql) throw new Error('seed_migration_out_of_date');
  console.log('Validated ten source policies and matching seed SQL.');
} else {
  writeFileSync(destination, sql);
  console.log(`Generated ${destination}`);
}
